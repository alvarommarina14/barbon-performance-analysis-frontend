// Regenerates the TypeScript view of the backend contract.
//
// The backend must be running: springdoc builds the spec from the live application context,
// so there is no way to produce it from source alone. Point OPENAPI_URL somewhere else to
// generate against a deployed environment.

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const source = process.env.OPENAPI_URL ?? 'http://localhost:8080/v3/api-docs';
const target = resolve(here, '../src/generated/schema.d.ts');

const banner = `/**
 * Generated by \`pnpm gen:api\` from ${source}
 *
 * Do not edit by hand. If a client stops compiling after regenerating, the backend
 * contract changed and the client has to catch up.
 */

`;

try {
  const ast = await openapiTS(new URL(source));
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, banner + astToString(ast), 'utf8');
  console.log(`Wrote ${target}`);
} catch (error) {
  console.error(`Could not read the OpenAPI spec from ${source}.`);
  console.error('Is the backend running? Try: cd backend && ./gradlew bootRun');
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}
